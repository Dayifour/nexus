const escape = (s: string) => s.replace(/[.*+?^$()|[\]\\]/g, "\\$&");
const EXACT = new Map(CATALOG.filter(([fr]) => !fr.includes("{}")));
const PATTERNS = CATALOG.filter(([fr]) => fr.includes("{}")).map(
  ([fr, en]) => [new RegExp(`^${fr.split("{}").map(escape).join("([\\s\\S]*?)")}$`), en] as const,
);

/** Traduit un message des services (français) dans la langue de l'utilisateur. */
export function localizeMessage(message: string, lang: Lang): string {
  if (lang === "fr") return message;
  // Préfixes ajoutés par la frontière (« Git : … ») : le préfixe est gardé, la suite traduite.
  const prefixed = /^(Git|GitHub|Vercel) : ([\s\S]*)$/.exec(message);
  if (prefixed) return `${prefixed[1]}: ${localizeMessage(prefixed[2]!, lang)}`;
  const exact = EXACT.get(message);
  if (exact) return exact;
  for (const [re, en] of PATTERNS) {
    const m = re.exec(message);
    if (!m) continue;
    let i = 1;
    return en.replace(/\{\}/g, () => m[i++] ?? "");
  }
  return message;
}

